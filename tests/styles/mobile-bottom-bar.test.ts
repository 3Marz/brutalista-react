// @vitest-environment node
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { describe, it, expect } from 'vitest';
import * as sass from 'sass';
import postcss, { type Root } from 'postcss';
import tailwindcss from 'tailwindcss';

const themeRoot = fileURLToPath(new URL('../../', import.meta.url));
const tailwindConfig = createRequire(import.meta.url)(`${themeRoot}tailwind.config.cjs`);

async function compile(file: string): Promise<Root> {
  const { css } = sass.compile(`${themeRoot}app/styles/04-components/${file}`);
  const result = await postcss([
    tailwindcss({ ...tailwindConfig, content: [{ raw: '' }] }),
  ]).process(css, { from: undefined });
  return result.root;
}

function declarations(root: Root, selector: string): Record<string, string> {
  const decls: Record<string, string> = {};
  root.walkRules((rule) => {
    if (rule.selectors.includes(selector)) {
      rule.walkDecls((decl) => {
        decls[decl.prop] = decl.value;
      });
    }
  });
  return decls;
}

describe('mobile bottom bar cart badge', () => {
  it("anchors to the cart icon's top-right corner", async () => {
    const root = await compile('mobile-bottom-bar.scss');
    const badge = declarations(root, '.mobile-bottom-bar__badge');

    expect(badge.top).toBe('-6px');
    expect(badge.right).toBe('-6px');
    expect(badge.bottom).toBe('auto');
    expect(badge.left).toBe('auto');
    expect(badge.transform).toBeUndefined();
  });
});
